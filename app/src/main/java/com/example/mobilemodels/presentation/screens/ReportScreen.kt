package com.example.mobilemodels.presentation.screens

import androidx.compose.foundation.layout.*
import androidx.compose.foundation.rememberScrollState
import androidx.compose.foundation.shape.RoundedCornerShape
import androidx.compose.foundation.verticalScroll
import androidx.compose.material.icons.Icons
import androidx.compose.material.icons.filled.Description
import androidx.compose.material.icons.filled.Download
import androidx.compose.material3.*
import androidx.compose.runtime.*
import androidx.compose.ui.Modifier
import androidx.compose.ui.graphics.Color
import androidx.compose.ui.text.font.FontWeight
import androidx.compose.ui.unit.dp
import com.example.mobilemodels.presentation.MobileModelsUiState
import com.example.mobilemodels.presentation.MobileModelsViewModel

private val BrandBlue = Color(0xFF1759D1)

@Composable
fun ReportScreen(
    state: MobileModelsUiState, vm: MobileModelsViewModel, onSave: () -> Unit
) {
    Column(
        Modifier.fillMaxSize().verticalScroll(rememberScrollState()).padding(20.dp),
        verticalArrangement = Arrangement.spacedBy(16.dp)
    ) {
        Text("Generated PDF Report", style = MaterialTheme.typography.titleLarge, fontWeight = FontWeight.Bold)
        ElevatedCard(shape = RoundedCornerShape(18.dp)) {
            Column(Modifier.padding(18.dp), verticalArrangement = Arrangement.spacedBy(12.dp)) {
                Icon(Icons.Default.Description, null, tint = BrandBlue, modifier = Modifier.size(42.dp))
                Text("Report download", style = MaterialTheme.typography.titleMedium, fontWeight = FontWeight.Bold)
                Text("Fetch the report generated by the FastAPI backend.")
                Button(onClick = vm::downloadReport, enabled = !state.isBusy, modifier = Modifier.fillMaxWidth()) {
                    Icon(Icons.Default.Download, null)
                    Spacer(Modifier.width(8.dp))
                    Text("Fetch PDF Report")
                }
                if (state.downloadedBytes != null && state.downloadedFileName == "mobile_models_report.pdf") {
                    Button(onClick = onSave, modifier = Modifier.fillMaxWidth()) { Text("Save Report PDF") }
                }
            }
        }
    }
}
